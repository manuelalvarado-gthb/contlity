package cloud.techmx.contlity.jdbc;

import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.SQLWarning;
import java.util.List;
import java.util.Map;

/** Sentencia de solo lectura (SELECT, WITH, TABLE, VALUES, EXPLAIN): una consulta por llamada. */
public class ContlityStatement extends BaseStatement {
    final ContlityConnection con;
    private ContlityResultSet actual;
    private boolean cerrada;
    private int maxRows, fetchSize, queryTimeout;
    private boolean closeOnCompletion;

    ContlityStatement(ContlityConnection con) {
        this.con = con;
    }

    void abierta() throws SQLException {
        if (cerrada) throw new SQLException("La sentencia está cerrada", "HY010");
        con.abierta();
    }

    @SuppressWarnings("unchecked")
    ContlityResultSet consultar(String sql) throws SQLException {
        abierta();
        cerrarActual();
        int pag = fetchSize > 0 ? Math.max(100, Math.min(100000, fetchSize)) : con.pagina;
        if (maxRows > 0 && maxRows < pag) pag = Math.max(1, maxRows);
        Map<String, Object> r = con.ejecutar(sql, pag, queryTimeout);
        List<Map<String, Object>> cols = (List<Map<String, Object>>) r.get("columns");
        List<Object> filas = (List<Object>) r.get("rows");
        Object rid = r.get("result_id");
        Object paginas = r.get("pages");
        Object total = r.get("total");
        actual = new ContlityResultSet(this, cols, filas, rid == null ? null : rid.toString(),
                paginas == null ? 1 : ((Number) paginas).intValue(), total == null ? -1 : ((Number) total).longValue(), maxRows);
        return actual;
    }

    void cerrarActual() throws SQLException {
        if (actual != null) {
            ContlityResultSet a = actual;
            actual = null;
            a.close();
        }
    }

    void resultadoCerrado(ContlityResultSet rs) throws SQLException {
        if (rs == actual) actual = null;
        if (closeOnCompletion) close();
    }

    @Override
    public ResultSet executeQuery(String sql) throws SQLException {
        return consultar(sql);
    }

    @Override
    public boolean execute(String sql) throws SQLException {
        consultar(sql);
        return true;
    }

    @Override
    public boolean execute(String sql, int autoGeneratedKeys) throws SQLException { return execute(sql); }

    @Override
    public boolean execute(String sql, int[] columnIndexes) throws SQLException { return execute(sql); }

    @Override
    public boolean execute(String sql, String[] columnNames) throws SQLException { return execute(sql); }

    @Override
    public int executeUpdate(String sql) throws SQLException {
        throw new SQLException("Contlity es de solo lectura por el driver: usa SELECT", "25006");
    }

    @Override
    public int executeUpdate(String sql, int autoGeneratedKeys) throws SQLException { return executeUpdate(sql); }

    @Override
    public int executeUpdate(String sql, int[] columnIndexes) throws SQLException { return executeUpdate(sql); }

    @Override
    public int executeUpdate(String sql, String[] columnNames) throws SQLException { return executeUpdate(sql); }

    @Override
    public ResultSet getResultSet() throws SQLException {
        abierta();
        return actual;
    }

    @Override
    public int getUpdateCount() throws SQLException {
        abierta();
        return -1;
    }

    @Override
    public boolean getMoreResults() throws SQLException {
        abierta();
        cerrarActual();
        return false;
    }

    @Override
    public boolean getMoreResults(int current) throws SQLException {
        return getMoreResults();
    }

    @Override
    public Connection getConnection() throws SQLException {
        abierta();
        return con;
    }

    @Override
    public void close() throws SQLException {
        if (cerrada) return;
        cerrarActual();
        cerrada = true;
    }

    @Override
    public boolean isClosed() { return cerrada; }

    @Override
    public void cancel() {}

    @Override
    public int getMaxRows() { return maxRows; }

    @Override
    public void setMaxRows(int max) throws SQLException {
        if (max < 0) throw new SQLException("maxRows negativo", "HY024");
        maxRows = max;
    }

    @Override
    public long getLargeMaxRows() { return maxRows; }

    @Override
    public void setLargeMaxRows(long max) throws SQLException { setMaxRows((int) Math.min(Integer.MAX_VALUE, max)); }

    @Override
    public int getFetchSize() { return fetchSize; }

    @Override
    public void setFetchSize(int rows) throws SQLException {
        if (rows < 0) throw new SQLException("fetchSize negativo", "HY024");
        fetchSize = rows;
    }

    @Override
    public int getFetchDirection() { return ResultSet.FETCH_FORWARD; }

    @Override
    public void setFetchDirection(int direction) throws SQLException {
        if (direction != ResultSet.FETCH_FORWARD) throw Util.noSoportado("recorrer hacia atrás");
    }

    @Override
    public int getQueryTimeout() { return queryTimeout; }

    @Override
    public void setQueryTimeout(int seconds) throws SQLException {
        if (seconds < 0) throw new SQLException("timeout negativo", "HY024");
        queryTimeout = seconds;
    }

    @Override
    public int getMaxFieldSize() { return 0; }

    @Override
    public void setMaxFieldSize(int max) {}

    @Override
    public void setEscapeProcessing(boolean enable) {}

    @Override
    public void setCursorName(String name) {}

    @Override
    public SQLWarning getWarnings() { return null; }

    @Override
    public void clearWarnings() {}

    @Override
    public int getResultSetConcurrency() { return ResultSet.CONCUR_READ_ONLY; }

    @Override
    public int getResultSetType() { return ResultSet.TYPE_FORWARD_ONLY; }

    @Override
    public int getResultSetHoldability() { return ResultSet.CLOSE_CURSORS_AT_COMMIT; }

    @Override
    public ResultSet getGeneratedKeys() { return ContlityResultSet.vacio(); }

    @Override
    public void setPoolable(boolean poolable) {}

    @Override
    public boolean isPoolable() { return false; }

    @Override
    public void closeOnCompletion() { closeOnCompletion = true; }

    @Override
    public boolean isCloseOnCompletion() { return closeOnCompletion; }

    @Override
    public void addBatch(String sql) throws SQLException { throw Util.noSoportado("addBatch"); }

    @Override
    public void clearBatch() {}

    @Override
    public int[] executeBatch() throws SQLException { throw Util.noSoportado("executeBatch"); }
}
