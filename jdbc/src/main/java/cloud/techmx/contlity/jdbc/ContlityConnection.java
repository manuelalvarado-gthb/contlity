package cloud.techmx.contlity.jdbc;

import java.sql.DatabaseMetaData;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.SQLWarning;
import java.sql.Statement;
import java.util.Collections;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Properties;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.Executor;

/** Conexión de solo lectura: cada sentencia es una llamada HTTPS a /v1/sql. */
public class ContlityConnection extends BaseConnection {
    final Api api;
    final String url;
    final int pagina;
    private volatile String database;
    private volatile String schema;
    private volatile boolean cerrada;
    private final Map<String, Object[]> catalogos = new ConcurrentHashMap<>();   // base → {instante, catálogo}
    private final Properties clientInfo = new Properties();

    ContlityConnection(Api api, String url, String database, String schema, int pagina) throws SQLException {
        this.api = api;
        this.url = url;
        this.database = database;
        this.schema = schema;
        this.pagina = pagina;
        catalogo(database);    // valida la API key y resuelve la base por omisión
    }

    // ── Llamadas ─────────────────────────────────────────────────────────────

    Map<String, Object> ejecutar(String sql, int pageSize, int timeoutS) throws SQLException {
        abierta();
        Map<String, Object> cuerpo = new LinkedHashMap<>();
        cuerpo.put("query", sql);
        cuerpo.put("page_size", pageSize);
        if (database != null) cuerpo.put("database", database);
        if (schema != null) cuerpo.put("schema_name", schema);
        int previo = api.timeout();
        if (timeoutS > 0) api.timeout(timeoutS);
        try {
            Map<String, Object> r = api.post("/sql", cuerpo);
            Object err = r.get("error");
            if (err != null) throw new SQLException(String.valueOf(err), "42000");
            return r;
        } finally {
            api.timeout(previo);
        }
    }

    @SuppressWarnings("unchecked")
    List<Object> pagina(String rid, int n) throws SQLException {
        abierta();
        return (List<Object>) api.get("/sql/results/" + rid + "/" + n, null).get("rows");
    }

    void liberar(String rid) {
        if (!cerrada) api.delete("/sql/results/" + rid);
    }

    /** Catálogo de una base (null = la principal), en caché 60 s. Sin costo ni límite por hora. */
    @SuppressWarnings("unchecked")
    Map<String, Object> catalogo(String base) throws SQLException {
        abierta();
        String k = base == null ? "" : base;
        Object[] c = catalogos.get(k);
        if (c != null && System.currentTimeMillis() - (long) c[0] < 60_000) return (Map<String, Object>) c[1];
        Map<String, String> q = new HashMap<>();
        if (base != null) q.put("database", base);
        Map<String, Object> r = api.get("/catalog", q);
        catalogos.put(k, new Object[]{System.currentTimeMillis(), r});
        if (base == null && database == null && r.get("database") != null) database = String.valueOf(r.get("database"));
        return r;
    }

    void abierta() throws SQLException {
        if (cerrada) throw new SQLException("La conexión está cerrada", "08003");
    }

    // ── Sentencias ───────────────────────────────────────────────────────────

    @Override
    public Statement createStatement() throws SQLException {
        abierta();
        return new ContlityStatement(this);
    }

    @Override
    public Statement createStatement(int tipo, int concurrencia) throws SQLException {
        return createStatement();
    }

    @Override
    public Statement createStatement(int tipo, int concurrencia, int holdability) throws SQLException {
        return createStatement();
    }

    @Override
    public PreparedStatement prepareStatement(String sql) throws SQLException {
        abierta();
        return new ContlityPreparedStatement(this, sql);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int tipo, int concurrencia) throws SQLException {
        return prepareStatement(sql);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int tipo, int concurrencia, int holdability) throws SQLException {
        return prepareStatement(sql);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException {
        return prepareStatement(sql);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, int[] columnIndexes) throws SQLException {
        return prepareStatement(sql);
    }

    @Override
    public PreparedStatement prepareStatement(String sql, String[] columnNames) throws SQLException {
        return prepareStatement(sql);
    }

    @Override
    public String nativeSQL(String sql) {
        return sql;
    }

    // ── Transacciones: solo lectura, sin transacción explícita ──────────────

    @Override
    public void setAutoCommit(boolean autoCommit) throws SQLException { abierta(); }

    @Override
    public boolean getAutoCommit() throws SQLException { abierta(); return true; }

    @Override
    public void commit() throws SQLException { abierta(); }

    @Override
    public void rollback() throws SQLException { abierta(); }

    @Override
    public void setReadOnly(boolean readOnly) throws SQLException { abierta(); }

    @Override
    public boolean isReadOnly() throws SQLException { abierta(); return true; }

    @Override
    public void setTransactionIsolation(int level) throws SQLException { abierta(); }

    @Override
    public int getTransactionIsolation() throws SQLException { abierta(); return TRANSACTION_READ_COMMITTED; }

    @Override
    public void setHoldability(int holdability) throws SQLException { abierta(); }

    @Override
    public int getHoldability() throws SQLException { return ResultSet.CLOSE_CURSORS_AT_COMMIT; }

    // ── Contexto: base (catálogo JDBC) y esquema ─────────────────────────────

    @Override
    public void setCatalog(String catalog) throws SQLException {
        abierta();
        if (catalog != null && !catalog.isEmpty()) database = catalog;
    }

    @Override
    public String getCatalog() throws SQLException {
        abierta();
        if (database == null) catalogo(null);
        return database;
    }

    @Override
    public void setSchema(String s) throws SQLException {
        abierta();
        schema = s == null || s.isEmpty() || s.equalsIgnoreCase(ContlityDatabaseMetaData.NUCLEO) ? null : s;
    }

    @Override
    public String getSchema() throws SQLException {
        abierta();
        return schema == null ? ContlityDatabaseMetaData.NUCLEO : schema;
    }

    @Override
    public DatabaseMetaData getMetaData() throws SQLException {
        abierta();
        return new ContlityDatabaseMetaData(this);
    }

    // ── Estado ───────────────────────────────────────────────────────────────

    @Override
    public void close() {
        cerrada = true;
        catalogos.clear();
    }

    @Override
    public boolean isClosed() {
        return cerrada;
    }

    @Override
    public void abort(Executor executor) {
        close();
    }

    @Override
    public boolean isValid(int timeout) throws SQLException {
        if (timeout < 0) throw new SQLException("timeout negativo", "HY000");
        if (cerrada) return false;
        if (System.currentTimeMillis() - api.ultimoOk < 30_000) return true;
        try {
            catalogos.remove(database == null ? "" : database);
            catalogo(database);
            return true;
        } catch (SQLException e) {
            return false;
        }
    }

    @Override
    public SQLWarning getWarnings() throws SQLException { abierta(); return null; }

    @Override
    public void clearWarnings() throws SQLException { abierta(); }

    @Override
    public Map<String, Class<?>> getTypeMap() { return Collections.emptyMap(); }

    @Override
    public void setTypeMap(Map<String, Class<?>> map) {}

    @Override
    public void setClientInfo(String name, String value) { if (name != null) clientInfo.setProperty(name, value == null ? "" : value); }

    @Override
    public void setClientInfo(Properties properties) { clientInfo.clear(); if (properties != null) clientInfo.putAll(properties); }

    @Override
    public String getClientInfo(String name) { return clientInfo.getProperty(name); }

    @Override
    public Properties getClientInfo() { return (Properties) clientInfo.clone(); }

    @Override
    public void setNetworkTimeout(Executor executor, int milliseconds) throws SQLException {
        abierta();
        if (milliseconds > 0) api.timeout(Math.max(1, milliseconds / 1000));
    }

    @Override
    public int getNetworkTimeout() { return api.timeout() * 1000; }
}
